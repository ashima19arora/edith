const quarters = (n: number) => {
  const whole = Math.floor(n);
  const part = n - whole;
  const mark = part >= 0.75 ? "¾" : part >= 0.5 ? "½" : part >= 0.25 ? "¼" : "";
  return `${whole > 0 || !mark ? whole : ""}${mark}`;
};

